    def test_browser_rotation_keeps_form_and_drawing(self):
        self.page.set_viewport_size({'width':820,'height':1180});self.ev('App.UI.applyResponsiveLayoutMode("auto",false)');self.ev('App.UI.navigateTo("viewNewEvent")')
        self.page.locator('#inputEventDescription').fill('Preservar durante rotação')
        self.page.locator('#btnToggleStylusCanvas').click()
        canvas=self.page.locator('#stylusDrawingCanvas');canvas.scroll_into_view_if_needed();r=canvas.bounding_box()
        self.page.mouse.move(r['x']+30,r['y']+30);self.page.mouse.down();self.page.mouse.move(r['x']+100,r['y']+80,steps=5);self.page.mouse.up()
        before=self.ev('App.UI.getStylusData()');self.assertTrue(before)
        self.page.set_viewport_size({'width':1180,'height':820});self.page.wait_for_timeout(100)
        self.assertEqual(self.page.locator('#inputEventDescription').input_value(),'Preservar durante rotação')
        self.assertTrue(self.ev('App.UI.getStylusData()'))
        ratio=self.ev('()=>{let c=document.getElementById("stylusDrawingCanvas"),r=c.getBoundingClientRect();return {bitmap:c.width/c.height,css:r.width/r.height}}')
        self.assertLess(abs(ratio['bitmap']-ratio['css']),0.03,ratio)

