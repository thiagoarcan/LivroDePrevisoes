    def test_modes_and_themes_persist_after_reload(self):
        for mode in ['auto','compact','mobile','tablet','conventional','widescreen','ultrawide']:
            self.page.evaluate('(m)=>App.UI.applyResponsiveLayoutMode(m,true)',mode)
            self.page.reload();self.page.wait_for_function('App.AlarmEngine.intervalId!==null');self.ev('App.AlarmEngine.stop()')
            self.assertEqual(self.ev('App.UI.responsiveLayoutMode'),mode)
        for theme in ['dark','light','industrial']:
            self.page.evaluate('async(t)=>{let s=await App.Service.getSettings();s.theme=t;await App.Service.saveSettings(s);App.UI.applyTheme(t)}',theme)
            self.page.reload();self.page.wait_for_function('App.AlarmEngine.intervalId!==null');self.ev('App.AlarmEngine.stop()')
            self.assertTrue(self.page.evaluate('(t)=>t==="dark"?!document.body.classList.contains("theme-light")&&!document.body.classList.contains("theme-industrial"):document.body.classList.contains("theme-"+t)',theme))
