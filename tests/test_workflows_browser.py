    def test_create_complete_reopen_duplicate_journey(self):
        self.ev('App.UI.navigateTo("viewNewEvent")')
        ids=self.ev('async()=>{let cs=await App.DB.getAll("consoles"),ps=await App.DB.getAll("pipelines"),us=await App.DB.getAll("operationalUnits");return {pipeline:ps.find(e=>e.name==="OSCAN").id,uo:us.find(e=>e.name==="REFAP").id}}')
        self.page.locator('#selectEventPipeline').select_option(ids['pipeline']);self.page.locator('#selectEventUO').select_option(ids['uo'])
        self.page.locator('#inputEventDescription').fill('Jornada completa de navegador')
        self.page.locator('#inputEventNotes').locator('xpath=ancestor::details').locator('summary').click()
        self.page.locator('#inputEventNotes').fill('Nota de teste com acentos e duas linhas.\nSegunda linha.')
        self.page.locator('#btnSubmitEvent').click()
        self.wait_db('async()=>(await App.DB.getAll("events")).some(e=>e.description==="Jornada completa de navegador")')
        event_id=self.ev('async()=>(await App.DB.getAll("events")).find(e=>e.description==="Jornada completa de navegador").id')
        self.page.evaluate('(id)=>App.UI.showCompleteModal(id)',event_id)
        self.page.locator('#inputCompleteNotes').fill('Concluído em teste')
        self.page.locator('#btnConfirmCompleteModal').click()
        self.wait_db('async()=>(await App.DB.getAll("events")).some(e=>e.description==="Jornada completa de navegador"&&e.status==="concluido")')
        self.page.evaluate('(id)=>App.UI.showReopenModal(id)',event_id);self.page.locator('#btnConfirmReopenModal').click()
        self.wait_db('async()=>(await App.DB.getAll("events")).some(e=>e.description==="Jornada completa de navegador"&&e.status==="pendente")')
        self.page.evaluate('(id)=>App.UI.duplicateEvent(id)',event_id)
        self.page.locator('#inputEventDescription').fill('Cópia da jornada')
        self.page.locator('#btnSubmitEvent').click()
