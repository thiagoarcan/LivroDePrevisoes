    def test_canvas_undo_eraser_and_confirmed_clear(self):
        self.ev('App.UI.navigateTo("viewNewEvent")');self.page.locator('#btnToggleStylusCanvas').click()
        canvas=self.page.locator('#stylusDrawingCanvas');canvas.scroll_into_view_if_needed()
        def draw():
            rect=canvas.bounding_box();self.page.mouse.move(rect['x']+40,rect['y']+45);self.page.mouse.down();self.page.mouse.move(rect['x']+150,rect['y']+75,steps=8);self.page.mouse.up()
        alpha='()=>{let c=App.UI.stylusCanvas,d=c.getContext("2d").getImageData(0,0,c.width,c.height).data,n=0;for(let i=3;i<d.length;i+=4)if(d[i])n++;return n}'
        draw();self.assertGreater(self.ev(alpha),0)
        self.page.locator('#btnUndoStylusCanvas').click();self.page.wait_for_timeout(80);self.assertEqual(self.ev(alpha),0)
        draw();before=self.ev(alpha);self.page.locator('#btnEraserStylusCanvas').click();draw()
        self.assertLess(self.ev(alpha),before)
        self.page.locator('#btnEraserStylusCanvas').click();draw();before=self.ev(alpha)
        self.page.locator('#btnClearStylusCanvas').click();self.page.wait_for_selector('#modalConfirm.active');self.page.locator('#btnCancelConfirm').click()
        self.assertEqual(self.ev(alpha),before)
        self.page.locator('#btnClearStylusCanvas').click();self.page.locator('#btnAcceptConfirm').click()
        self.assertEqual(self.ev(alpha),0);self.assertEqual(self.errors,[])

